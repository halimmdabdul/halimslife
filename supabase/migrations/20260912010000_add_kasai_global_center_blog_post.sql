জাপানের কাসাই শহরে তখন আমার নতুন জীবন শুরু হয়েছে। চারপাশের সবকিছুই অচেনা—ভাষা, মানুষ, খাবার, রাস্তাঘাট; এমনকি বাতাসের গন্ধটাও যেন আলাদা।

শহর হলেও কাসাইয়ের অনেক জায়গায় একধরনের গ্রামীণ নীরবতা আছে। দূরে পাহাড়, পাশে ধানখেত, ফাঁকা রাস্তা আর সারি সারি পরিপাটি বাড়ি। ব্যস্ততা নেই, মানুষের ভিড় নেই—আছে কেবল শান্তি আর গভীর নিস্তব্ধতা।

## সেই বিকেলের হাঁটা

সেদিন কোনো বিশেষ উদ্দেশ্য ছাড়াই হাঁটতে বেরিয়েছিলাম। নতুন একটি জায়গাকে চেনার জন্য হাঁটার চেয়ে ভালো উপায় আর কী হতে পারে? ধীরে ধীরে পথ চলছিলাম, চারপাশ দেখছিলাম। কখনো কোনো দোকানের সাইনবোর্ড বোঝার চেষ্টা করছি, আবার কখনো অচেনা গাছপালা আর বাড়িগুলোর দিকে তাকিয়ে ভাবছি—বাংলাদেশ থেকে কত দূরে চলে এসেছি!

হঠাৎ আমার চোখ থেমে গেল।

দূরে যেন পরিচিত দুটি রঙ—সবুজের মাঝে একটি লাল বৃত্ত।

প্রথমে ভাবলাম, হয়তো চোখের ভুল। বিদেশে এসে মন কি তবে নিজের দেশকেই সব জায়গায় খুঁজে বেড়াচ্ছে?

আমি আরেকটু সামনে এগিয়ে গেলাম।

না, চোখের ভুল নয়। **ওটা সত্যিই বাংলাদেশের জাতীয় পতাকা!**

## এই নির্জন শহরে বাংলাদেশের পতাকা?

কয়েক মুহূর্তের জন্য আমি একেবারে স্থির হয়ে দাঁড়িয়ে রইলাম। মনে শুধু একটি প্রশ্ন—

> জাপানের এমন শান্ত, গ্রামঘেঁষা একটি শহরে বাংলাদেশের পতাকা এল কোথা থেকে?

আমার বিস্ময়ের সঙ্গে কৌতূহলও বাড়ছিল। পা দুটি যেন নিজেদের ইচ্ছাতেই পতাকাটির দিকে এগিয়ে যাচ্ছিল। যত কাছে যাচ্ছি, ততই স্পষ্ট হয়ে উঠছে সেই চিরচেনা লাল-সবুজ।

বিদেশের মাটিতে নিজের দেশের পতাকা দেখার অনুভূতি ভাষায় প্রকাশ করা কঠিন। বাংলাদেশে থাকতে যে পতাকা প্রতিদিন দেখেও হয়তো আলাদাভাবে খেয়াল করিনি, হাজার হাজার কিলোমিটার দূরে সেই একই পতাকাই মুহূর্তের মধ্যে আমার বুকের ভেতর আলোড়ন তুলল।

মনে হলো, আমি আর একা নই।

এই অচেনা শহরের কোথাও আমার দেশেরও একটি পরিচয় আছে। এখানে কেউ বাংলাদেশকে জানে, কেউ বাংলাভাষী মানুষের কথা ভাবে—এই উপলব্ধিটুকুই যেন কাসাইকে হঠাৎ আমার কাছে অনেকটা আপন করে দিল।

## পতাকাটির পেছনে যে ঠিকানা

আরও কাছে গিয়ে জানতে পারলাম, এটি [Kasai City Global Center](https://kasai-globalcenter.jp/)—জাপানি নাম **加西市グローバルセンター**।

এটি শুধু বিভিন্ন দেশের পতাকা প্রদর্শনের একটি স্থান নয়। বিদেশি ও জাপানি বাসিন্দাদের মধ্যে পারস্পরিক বোঝাপড়া তৈরি করা এবং সবাই যেন নিরাপদে একসঙ্গে বসবাস করতে পারে—সেই লক্ষ্যেই কেন্দ্রটি কাজ করে।

এখানে বহুভাষিক পরামর্শ, জাপানি ভাষা শেখার সুযোগ, বিদেশি শিশুদের পড়াশোনায় সহায়তা এবং বিভিন্ন সাংস্কৃতিক বিনিময় অনুষ্ঠানের ব্যবস্থা রয়েছে। সবচেয়ে আনন্দের বিষয়, কেন্দ্রটির বহুভাষিক পরামর্শসেবার তালিকায় **বাংলা ভাষাও রয়েছে**। কেন্দ্রটির [সেবাসমূহ](https://kasai-globalcenter.jp/services/) সম্পর্কে তাদের ওয়েবসাইটে বিস্তারিত জানা যায়।

সেদিন বুঝতে পারলাম, পতাকাটি সেখানে শুধু সাজানোর জন্য ছিল না। সেটি ছিল একটি বার্তা—

> **তুমি যে দেশ থেকেই আসো না কেন, এই শহরে তোমারও একটি স্থান আছে।**

## কাসাই এখনো আমার ঠিকানা

এই গল্পটি কেবল কাসাইয়ে আসার প্রথম দিনগুলোর একটি পুরোনো স্মৃতি নয়। **আমি এখনও কাসাইতেই থাকি।** সময়ের সঙ্গে এই শহরের নিরিবিলি পথ, চারপাশের প্রকৃতি আর শান্ত জীবনযাত্রা আমার খুব পছন্দের হয়ে উঠেছে। কাসাই আর আমার কাছে নতুন বা অচেনা নয়—এটি আমার প্রতিদিনের জীবনের অংশ।

আর Kasai City Global Center-এর সঙ্গেও আমার সম্পর্ক সেই প্রথম বিস্ময়ের দিনে শেষ হয়ে যায়নি। কেন্দ্রটির বিভিন্ন অনুষ্ঠান ও আয়োজন, এবং নানা মানুষের সঙ্গে মিলিত হওয়ার উষ্ণ পরিবেশ আমার খুব ভালো লাগে। **প্রতি সপ্তাহান্তেই আমি সেখানে যাই।** প্রতিবারই মনে হয়, পৃথিবীর নানা দেশের মানুষকে একে অন্যের কাছে আনার যে বার্তা সেই পতাকাটি দিয়েছিল, কেন্দ্রটি এখনো সেই বার্তাকে বাস্তবে রূপ দিয়ে চলেছে।

## কাসাইকে আরও একটু চেনা

পরে কাসাই সম্পর্কে জানতে গিয়ে বুঝেছি, সেদিনের সেই শান্ত দৃশ্যটি কাসাইয়ের পরিচয়েরই অংশ। এই শহরের মধ্য দিয়ে চলে যাওয়া **Hojo Railway** ১৯১৫ সালে যাত্রা শুরু করে। এক লাইনের এই লোকাল রেলপথ মোট ১৩.৬ কিলোমিটার দূরত্বে আটটি স্টেশনকে যুক্ত করেছে। Hojomachi ছাড়া বাকি স্টেশনগুলো জনবলহীন। এক কামরার ছোট ট্রেনটি ধানখেত ও গ্রামীণ প্রকৃতির ভেতর দিয়ে যায়—মনে হয়, সময়ও যেন তার সঙ্গে ধীর হয়ে যায়।

ট্রেনের জানালা থেকে দেখা যায় শস্যক্ষেত্র, নিরিবিলি প্রকৃতি আর Zenbo ও Kasamatsu পাহাড়—যেগুলোকে একসঙ্গে **Kasai Alps** বলা হয়। পাহাড়ে হাইকিংয়ের পথও আছে। আর Hojōchō এলাকায় রয়েছে ১,৩০০ বছরেরও বেশি পুরোনো Sumiyoshi Shrine, Sagamiji Temple এবং রহস্যময় **500 Rakan** পাথরের মূর্তি। পুরোনো post-town ও temple-town হিসেবে গড়ে ওঠা এলাকাটির পথঘাটে হাঁটলে জাপানের পুরোনো সময়ের আমেজ এখনও অনুভব করা যায়।

এসব তথ্য পড়ে সেদিনের হাঁটাটিকে যেন আরও নতুনভাবে দেখতে পারি। যে নীরবতা প্রথমে আমার কাছে নিছক একটি দূরবর্তী গ্রামীণ শহরের নীরবতা মনে হয়েছিল, তার ভেতরেই লুকিয়ে আছে কাসাইয়ের রেলগাথা, ইতিহাস আর মানুষের ভালোবাসা। কাসাই ভ্রমণের আরও বিস্তারিত তথ্য পাওয়া যাবে [Visit HYOGO-এর অফিসিয়াল ভ্রমণ নিবন্ধে](https://www.hyogo-tourism.jp/world/feature/detail_109.html)।

## দূরত্ব ঘুচিয়ে দেওয়া এক মুহূর্ত

একজন প্রবাসীর জীবনে এমন ছোট ছোট মুহূর্তের মূল্য অনেক। নতুন দেশে এসে নিজের পরিচয় বোঝানো, ভাষার বাধা পেরোনো এবং একাকিত্বের সঙ্গে লড়াই করা সহজ নয়। বাইর থেকে সবকিছু সুন্দর ও গোছানো দেখালেও মনের ভেতর মাঝেমধ্যে গভীর শূন্যতা তৈরি হয়।

ঠিক সেই সময় পরিচিত একটি শব্দ, নিজের ভাষায় লেখা একটি বাক্য কিংবা দেশের একটি পতাকা মনে অদ্ভুত সাহস এনে দেয়।

সেদিন বাংলাদেশের পতাকাটির দিকে তাকিয়ে আমার গ্রামের কথা মনে পড়েছিল। মনে পড়েছিল সবুজ ধানখেত, বর্ষার বৃষ্টি, চায়ের দোকানের আড্ডা এবং প্রিয় মানুষগুলোর মুখ। কয়েক সেকেন্ডের জন্য মনে হয়েছিল, কাসাই আর বাংলাদেশ—দুই দূর দেশের মাঝখানের বিশাল দূরত্ব যেন হঠাৎ অনেকটাই কমে গেছে।

আমি আবার হাঁটতে শুরু করলাম। রাস্তা একই ছিল, শহরটিও বদলে যায়নি। কিন্তু বদলে গিয়েছিল আমার দেখার চোখ।

কাসাই তখন আর শুধু জাপানের একটি অচেনা শহর ছিল না। এটি হয়ে উঠেছিল এমন একটি শহর, যেখানে পৃথিবীর নানা দেশের মানুষের পাশে বাংলাদেশের জন্যও একটু জায়গা রাখা হয়েছে।

